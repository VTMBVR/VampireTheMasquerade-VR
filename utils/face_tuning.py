"""Validated local persistence for the in-game facial editor."""
import json
import math
import os
from pathlib import Path
import tempfile


def specifications(checkout):
    return json.loads((checkout/'scripts/dialogue/face_editor.json').read_text(encoding='utf-8-sig'))


def validate_settings(tuning, shapes, controllers, checkout):
    limits = {v['key']: v for v in specifications(checkout)['controls']}
    if not isinstance(tuning, dict) or set(tuning) != set(limits):
        raise ValueError('Missing or unknown facial settings')
    if not isinstance(shapes, dict) or set(shapes)-set(controllers):
        raise ValueError('Unknown facial shape')
    for key, value in tuning.items():
        spec = limits[key]
        if type(value) not in (int, float) or not math.isfinite(value) or not spec['min'] <= value <= spec['max']:
            raise ValueError('Invalid facial setting: '+key)
    for key, value in shapes.items():
        if type(value) not in (int, float) or not math.isfinite(value) or not 0 <= value <= 1:
            raise ValueError('Invalid facial shape gain: '+key)
    return dict(tuning), {k: v for k, v in shapes.items() if v != 1}


def atomic_write(path, content):
    temp = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as stream:
            temp = Path(stream.name)
            stream.write(content)
        os.replace(temp, path)
    finally:
        if temp is not None and temp.exists():
            temp.unlink()


def save_settings(payload, checkout=None):
    checkout = Path(checkout) if checkout else Path(__file__).resolve().parents[1]
    request = payload.get('request')
    if type(request) is not int or not 0 <= request <= 2147483647:
        raise ValueError('Invalid facial save request')
    source = checkout/'scripts/dialogue/jeanette.json'
    catalog = checkout/'scripts/dialogue/jeanette_lipsync.json'
    lua_file = checkout/'scripts/vscripts/npc_dialog_lipsync_data.lua'
    original = {p: p.read_bytes() for p in (source, catalog, lua_file)}
    conversation = json.loads(original[source].decode('utf8'))
    data = json.loads(original[catalog].decode('utf8'))
    tuning, shapes = validate_settings(payload.get('tuning'), payload.get('shapeGains'), data['faceControllers'], checkout)
    conversation['faceTuning'], conversation['faceShapeGains'] = tuning, shapes
    data['tuning'], data['shapeGains'] = tuning, shapes
    from build_jeanette_face import lua
    prepared = {
        catalog: (json.dumps(data, ensure_ascii=False, indent=2)+'\n').encode('utf8'),
        lua_file: ('-- Generated by utils/build_jeanette_face.py from original Bloodlines data.\nreturn '+lua(data)+'\n').encode('utf8'),
        source: (json.dumps(conversation, ensure_ascii=False, indent=2)+'\n').encode('utf8'),
    }
    written = []
    try:
        for path, content in prepared.items():
            atomic_write(path, content)
            written.append(path)
    except Exception:
        for path in reversed(written):
            atomic_write(path, original[path])
        raise
    return request
